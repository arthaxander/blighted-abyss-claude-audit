export const equipmentByName = equipment.reduce((acc, item) => {
  acc[item.name] = item;
  (item.legacyNames || []).forEach(legacyName => {
    acc[legacyName] = { ...item, name: legacyName, canonicalName: item.name };
  });
  return acc;
}, {});

export const getMagicSchoolFromEquipment = (names = []) => {
  if (!Array.isArray(names)) return null;
  for (const name of names) {
    const def = equipmentByName[name];
    if (def?.type === 'Weapon' && def.magicSchool) {
      return def.magicSchool;
    }
  }
  return null;
};

