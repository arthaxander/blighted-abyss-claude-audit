const relicMap = RELIC_DEFINITIONS.reduce((acc, relic) => {
  acc[relic.id] = relic;
  return acc;
}, {});

export const getRelicDefinitions = () => RELIC_DEFINITIONS;
export const getRelicById = (id) => relicMap[id];

export const ensureRelicState = (raw = {}) => {
  // Backward compatibility: legacy save stored { recruitSeal: { level, xp } }
  const legacy = raw.recruitSeal ? { [DEFAULT_RELIC_ID]: raw.recruitSeal } : {};
  const progress = { ...(raw.progress || legacy) };
  if (!progress[DEFAULT_RELIC_ID]) {
    progress[DEFAULT_RELIC_ID] = { level: 1, xp: 0 };
  } else {
    const recruitProgress = progress[DEFAULT_RELIC_ID] || {};
    const level = Math.max(1, Math.min(15, Math.floor(Number(recruitProgress.level) || 0)));
    progress[DEFAULT_RELIC_ID] = {
      ...recruitProgress,
      level,
      xp: level === 15 ? 0 : Math.max(0, Number(recruitProgress.xp) || 0),
    };
  }
  const requestedActiveRelicId = raw.activeRelicId || raw.activeId || DEFAULT_RELIC_ID;
  const activeRelicId = relicMap[requestedActiveRelicId] ? requestedActiveRelicId : DEFAULT_RELIC_ID;
  const discoveredRelicIds = [...new Set([
    DEFAULT_RELIC_ID,
    ...(Array.isArray(raw.discoveredRelicIds) ? raw.discoveredRelicIds : []),
    ...Object.keys(progress),
    activeRelicId,
  ])].filter(id => Boolean(relicMap[id]));
  return {
    activeRelicId,
    discoveredRelicIds,
    progress,
  };
};

export const grantAllRelics = (raw = {}) => ({
  ...ensureRelicState(raw),
  discoveredRelicIds: RELIC_DEFINITIONS.map(relic => relic.id),
});

export function resolveRelicProgress(progress = { level: 0, xp: 0 }, xpGained = 0, relicId = DEFAULT_RELIC_ID) {
  let xp = (progress?.xp ?? 0) + xpGained;
  let level = progress?.level ?? 0;
  const maxLevel = xpPerLevel > 0 ? (getRelicById(relicId)?.levels.length || 10) : 0;
  const levelUps = [];

  while (level < maxLevel && xp >= xpPerLevel) {
    xp -= xpPerLevel;
    level += 1;
    levelUps.push(level);
  }

  if (level >= maxLevel) {
    level = maxLevel;
    xp = 0;
  }

  return { level, xp, levelUps };
}

export function grantRelicExperience(relicState = ensureRelicState(), relicId = DEFAULT_RELIC_ID, xpGained = 0) {
  const ensured = ensureRelicState(relicState);
  const targetId = relicId || ensured.activeRelicId || DEFAULT_RELIC_ID;
  const current = ensured.progress?.[targetId] || { level: 0, xp: 0 };
  const progress = resolveRelicProgress(current, xpGained, targetId);
  return {
    relicState: {
      ...ensured,
      activeRelicId: ensured.activeRelicId || targetId,
      progress: {
        ...ensured.progress,
        [targetId]: { level: progress.level, xp: progress.xp },
      },
    },
    levelUps: progress.levelUps,
  };
}

export const describeRelicLevel = (relicId, level) => {
  const relic = getRelicById(relicId);
  if (!relic || !level || level < 1 || level > relic.levels.length) return null;
  return relic.levels[level - 1].description;
};

export const getNextRelicDescription = (relicId, level) => {
  const relic = getRelicById(relicId);
  if (!relic) return null;
  const next = level + 1;
  if (next > relic.levels.length) return null;
  return relic.levels[next - 1].description;
};

export function getRecruitSealBonuses(level = 0) {
  const bonuses = {
    startTurnMeter: 0, consumableTurnMeter: 0, firstConsumableTurnMeter: 0,
    preserveConsumableChance: 0, insuranceChance: 0, extraLootChance: 0,
  };

  if (level <= 0) {
    return bonuses;
  }

  bonuses.startTurnMeter = level >= 14 ? 0.4 : level >= 8 ? 0.25 : level >= 2 ? 0.15 : 0.1;
  bonuses.consumableTurnMeter = level >= 15 ? 0.2 : level >= 12 ? 0.15 : level >= 6 ? 0.1 : level >= 3 ? 0.05 : 0;
  bonuses.firstConsumableTurnMeter = level >= 14 ? 0.3 : level >= 9 ? 0.2 : level >= 5 ? 0.1 : 0;
  bonuses.preserveConsumableChance = level >= 15 ? 0.35 : level >= 12 ? 0.25 : level >= 7 ? 0.15 : level >= 4 ? 0.1 : 0;
  bonuses.insuranceChance = level >= 15 ? 1 : level >= 10 ? 0.5 : 0;
  bonuses.extraLootChance = level >= 13 ? 0.25 : level >= 11 ? 0.1 : 0;

  return bonuses;
}

export const getRelicBonuses = (relicId, level = 0) => {
  if (relicId === DEFAULT_RELIC_ID) {
    return getRecruitSealBonuses(level);
  }
  // Новые реликвии пока дают описательные эффекты без числовых модификаторов
  return {};
};

export const getRelicMagicSchool = (relicId, fallback = DEFAULT_MAGIC_SCHOOL) => {
  const relic = getRelicById(relicId);
  if (!relic) return fallback;
  if (relicId === 'blazing_talisman') return 'fire';
  if (relicId === 'storm_inferno' || relicId === 'storm_coil') return 'lightning';
  if (relicId === 'frozen_heart') return 'ice';
  return fallback;
};
